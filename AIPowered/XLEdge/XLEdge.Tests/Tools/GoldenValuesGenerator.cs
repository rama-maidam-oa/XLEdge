using System;
using System.IO;
using System.Linq;
using System.Reflection;

internal static class Program
{
    private static int Main(string[] args)
    {
        string dll = args[0], output = args[1];
        Assembly xledge = Assembly.LoadFrom(dll);
        string[] lines = XLEdge.Tests.GoldenCases.Run(xledge);
        using (var w = new StreamWriter(output, false, new System.Text.UTF8Encoding(false)))
        {
            w.WriteLine("// <auto-generated> by Tools\\GoldenValuesGenerator.cs from XLEdge 11.1.2's XLEdge.dll (bin\\Debug, 27-Oct-2026 22:55):");
            w.WriteLine("// the outputs of GoldenCases. Culture data (de-DE, th-TH) and double formatting are this Windows build's; the UI");
            w.WriteLine("// culture is pinned to en-US. Some values pin 11.1.2 defects on purpose (see the Stage 2b ledger rulings): the core");
            w.WriteLine("// keeps 11.1.2's behaviour until they are fixed in 11.1.2 first. Regenerate only when that behaviour is meant to change. </auto-generated>");
            w.WriteLine("namespace XLEdge.Tests");
            w.WriteLine("{");
            w.WriteLine("    internal static class GoldenValues");
            w.WriteLine("    {");
            w.WriteLine("        public static readonly string[] Lines =");
            w.WriteLine("        {");
            foreach (string line in lines) w.WriteLine("            @\"" + line.Replace("\"", "\"\"") + "\",");
            w.WriteLine("        };");
            w.WriteLine("    }");
            w.WriteLine("}");
        }
        Console.WriteLine(lines.Length + " golden values written; first: " + lines.First());
        return 0;
    }
}
